import React, { useState, useEffect } from 'react';
import { useAuth } from '../../context/AuthContext';
import { meApi } from '../../api';
import { Payslip } from '../../types';
import { getMonthName } from '../../utils/dateUtils';
import {
  FileText,
  Download,
  Lock,
  Eye,
  CheckCircle2,
  ShieldCheck,
  Building2,
  AlertCircle,
  Printer
} from 'lucide-react';
import { StatusPill } from '../common/StatusPill';
import { Modal } from '../common/Modal';
import { SkeletonLoader } from '../common/SkeletonLoader';
import { AttendancePayslips } from './AttendancePayslips';
import { PayslipView } from '../common/PayslipView';

export const MyPayslips: React.FC = () => {
  const { currentUser, showToast } = useAuth();
  const [loading, setLoading] = useState(true);
  const [year, setYear] = useState(2026);
  const [payslipsList, setPayslipsList] = useState<Array<Pick<Payslip, 'id' | 'year' | 'month' | 'source' | 'status' | 'publishedAt'>>>([]);
  const [activePayslipDoc, setActivePayslipDoc] = useState<Payslip | null>(null);
  const [viewingId, setViewingId] = useState<number | null>(null);

  const fetchPayslips = async () => {
    try {
      setLoading(true);
      const data = await meApi.getPayslips(year);
      setPayslipsList(data);
    } catch (err: any) {
      showToast('Error', err.message || 'Failed to load payslips', 'error');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchPayslips();
  }, [year, currentUser?.id]);

  const handleOpenPayslip = async (id: number) => {
    setViewingId(id);
    try {
      const doc = await meApi.getPayslipDocument(id);
      setActivePayslipDoc(doc);
      showToast('Access Logged', 'Payslip retrieved. Immutable audit record created for Accounts compliance.', 'info');
    } catch (err: any) {
      showToast('Access Denied', err.message || 'Unable to open payslip', 'error');
    } finally {
      setViewingId(null);
    }
  };

  const numberToWords = (num: number): string => {
    // Simple INR converter for clean payslip display
    if (num <= 0) return 'Zero';
    const a = ['', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten', 'Eleven', 'Twelve', 'Thirteen', 'Fourteen', 'Fifteen', 'Sixteen', 'Seventeen', 'Eighteen', 'Nineteen'];
    const b = ['', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'];
    
    const inWords = (n: number): string => {
      if (n < 20) return a[n];
      if (n < 100) return b[Math.floor(n / 10)] + (n % 10 !== 0 ? ' ' + a[n % 10] : '');
      if (n < 1000) return a[Math.floor(n / 100)] + ' Hundred' + (n % 100 !== 0 ? ' ' + inWords(n % 100) : '');
      if (n < 100000) return inWords(Math.floor(n / 1000)) + ' Thousand' + (n % 1000 !== 0 ? ' ' + inWords(n % 1000) : '');
      if (n < 10000000) return inWords(Math.floor(n / 100000)) + ' Lakh' + (n % 100000 !== 0 ? ' ' + inWords(n % 100000) : '');
      return inWords(Math.floor(n / 10000000)) + ' Crore' + (n % 10000000 !== 0 ? ' ' + inWords(n % 10000000) : '');
    };
    return inWords(num) + ' Rupees Only';
  };

  return (
    <div className="px-4 sm:px-8 py-6 sm:py-8 max-w-7xl mx-auto space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-end justify-between gap-4 pb-1">
        <div>
          <div className="flex items-center gap-2">
            <h1 className="text-[22px] sm:text-2xl font-semibold text-slate-900 dark:text-slate-50">Confidential Salary Slips</h1>
            <span className="text-xs px-2 py-0.5 rounded font-bold bg-amber-50 dark:bg-amber-950/40 text-amber-800 dark:text-amber-300 border border-amber-200 dark:border-amber-800/70 flex items-center gap-1">
              <Lock className="w-3 h-3" /> Encrypted Vault
            </span>
          </div>
          <p className="text-sm text-slate-500 dark:text-slate-400 mt-1 max-w-[70ch]">
            Official monthly compensation receipts generated by Accounts Department
          </p>
        </div>

        {/* Year filter */}
        <div className="flex items-center gap-2">
          <label className="text-xs font-semibold text-slate-600 dark:text-slate-400">Financial Year:</label>
          <select
            value={year}
            onChange={e => setYear(Number(e.target.value))}
            className="text-xs p-2 rounded-lg border border-slate-300 dark:border-slate-700 font-bold bg-white dark:bg-slate-900 text-slate-800 dark:text-slate-200 focus:outline-none focus:ring-1 focus:ring-teal-700"
          >
            <option value={2026}>2026</option>
            <option value={2025}>2025</option>
          </select>
        </div>
      </div>

      {/* Security notice */}
      <div className="p-3 rounded-lg bg-teal-50/70 dark:bg-teal-950/40 border border-teal-200 dark:border-teal-800/70 text-xs text-teal-900 dark:text-teal-200 flex items-center justify-between">
        <div className="flex items-center gap-2">
          <ShieldCheck className="w-4 h-4 text-teal-700 dark:text-teal-300 flex-shrink-0" />
          <span>
            <strong>Zero-Knowledge List:</strong> Amounts are not rendered in the summary table to prevent shoulder-surfing. Every document access is immutably timestamped in the audit vault.
          </span>
        </div>
      </div>

      {/* Attendance-computed payslips & salary history */}
      <AttendancePayslips />

      {/* Table of Payslips */}
      {loading ? (
        <SkeletonLoader type="table" rows={4} />
      ) : payslipsList.length === 0 ? (
        <div className="bg-white dark:bg-slate-900 p-12 text-center rounded-xl border border-slate-200 dark:border-slate-800 shadow-xs">
          <FileText className="w-10 h-10 text-slate-300 mx-auto mb-2" />
          <h3 className="text-sm font-bold text-slate-800 dark:text-slate-200">No Published Payslips for {year}</h3>
          <p className="text-xs text-slate-500 dark:text-slate-400 mt-1">
            Accounts publishes payslips between the 1st and 5th of each calendar month.
          </p>
        </div>
      ) : (
        <div className="bg-white dark:bg-slate-900 rounded-xl border border-slate-200 dark:border-slate-800 overflow-hidden shadow-xs">
          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs text-slate-700 dark:text-slate-300">
              <thead className="bg-slate-50 dark:bg-slate-800/50 border-b border-slate-200 dark:border-slate-800 text-slate-600 dark:text-slate-400 text-[12.5px] font-bold">
                <tr>
                  <th className="px-5 py-3.5">Month / Year</th>
                  <th className="px-5 py-3.5">Document Origin</th>
                  <th className="px-5 py-3.5">Publication Status</th>
                  <th className="px-5 py-3.5">Published Date</th>
                  <th className="px-5 py-3.5 text-right">Encrypted Action</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                {payslipsList.map(slip => (
                  <tr key={slip.id} className="hover:bg-slate-50/80 dark:hover:bg-slate-800/50 transition-colors">
                    <td className="px-5 py-4 font-bold text-slate-900 dark:text-slate-100">
                      {getMonthName(slip.month)} {slip.year}
                    </td>
                    <td className="px-5 py-4">
                      <span className="text-xs font-mono font-medium px-2 py-0.5 rounded bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300">
                        {slip.source === 'GENERATED' ? 'System Engine (Spring/DB)' : 'Accounts Bulk PDF'}
                      </span>
                    </td>
                    <td className="px-5 py-4">
                      <StatusPill status={slip.status} />
                    </td>
                    <td className="px-5 py-4 text-slate-500 dark:text-slate-400 font-mono">
                      {slip.publishedAt ? new Date(slip.publishedAt).toLocaleDateString('en-GB') : '—'}
                    </td>
                    <td className="px-5 py-4 text-right">
                      <button
                        onClick={() => handleOpenPayslip(slip.id)}
                        disabled={viewingId === slip.id}
                        className="px-3.5 py-1.5 text-xs font-semibold rounded-lg bg-teal-700 text-white hover:bg-teal-800 transition-colors inline-flex items-center gap-1.5 shadow-xs"
                      >
                        <Eye className="w-3.5 h-3.5" />
                        {viewingId === slip.id ? 'Decrypting...' : 'View & Download'}
                      </button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {/* Official Payslip Document Modal */}
      {activePayslipDoc && (
        <Modal
          isOpen={!!activePayslipDoc}
          onClose={() => setActivePayslipDoc(null)}
          title={`Official Salary Statement: ${getMonthName(activePayslipDoc.month)} ${activePayslipDoc.year}`}
          subtitle={`Confidential to ${activePayslipDoc.employeeName} (${activePayslipDoc.employeeCode})`}
          maxWidth="2xl"
        >
          <PayslipView
            entry={{
              year: activePayslipDoc.year,
              month: activePayslipDoc.month,
              calendarDays: new Date(activePayslipDoc.year, activePayslipDoc.month, 0).getDate(),
              payableDays: activePayslipDoc.paidDays,
              presentDays: activePayslipDoc.paidDays,
              paidLeaveDays: 0,
              holidayDays: 0,
              weekOffDays: 0,
              lopDays: activePayslipDoc.lopDays,
              lateMarks: 0,
              earnings: [
                { code: 'BASIC', label: 'Basic Salary', amount: activePayslipDoc.components.basic },
                { code: 'HRA', label: 'House Rent Allowance (HRA)', amount: activePayslipDoc.components.hra },
                { code: 'SPECIAL', label: 'Special / Medical Allowance', amount: activePayslipDoc.components.specialAllowance }
              ],
              deductions: [
                { code: 'PF', label: 'Provident Fund (EPF)', amount: activePayslipDoc.components.pf },
                { code: 'PT', label: 'Professional Tax (PT)', amount: activePayslipDoc.components.pt },
                { code: 'TDS', label: 'Income Tax (TDS)', amount: activePayslipDoc.components.tds },
                ...(activePayslipDoc.components.lopDeduction > 0
                  ? [{ code: 'LOP', label: 'Loss of Pay Deduction', amount: activePayslipDoc.components.lopDeduction }]
                  : [])
              ],
              grossEarnings: activePayslipDoc.grossAmount,
              totalDeductions: activePayslipDoc.totalDeductions,
              netPay: activePayslipDoc.netAmount
            }}
            employeeId={activePayslipDoc.employeeId}
            employee={{
              name: activePayslipDoc.employeeName,
              code: activePayslipDoc.employeeCode,
              designation: activePayslipDoc.designation,
              department: activePayslipDoc.departmentName
            }}
            status={activePayslipDoc.status}
          />
        </Modal>
      )}
    </div>
  );
};
