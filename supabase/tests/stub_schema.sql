-- staff-lifecycle migration's RLS policies and triggers on a throwaway database.
-- Minimal Supabase-like stub
do $$ begin create role authenticated nologin; exception when duplicate_object then null; end $$;
do $$ begin create role anon nologin; exception when duplicate_object then null; end $$;
create schema auth;
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb $$;
grant usage on schema auth to authenticated;
grant usage on schema public to authenticated;

create type app_role as enum ('EMPLOYEE','MANAGER','HR','ACCOUNTS','CEO','SYSTEM_ADMIN','DIRECTOR');
create table departments (id bigint generated by default as identity primary key, entity_id int default 1, name text not null, head_id bigint);
create table employees (
  id bigint generated by default as identity primary key, auth_user_id uuid, emp_code text unique not null, entity_id int,
  full_name text not null, official_email text unique not null, personal_email text, mobile text, phone text,
  department_id bigint references departments(id), designation text, employment_type text, date_of_joining date, date_of_exit date,
  work_location text, status text default 'ACTIVE', manager_id bigint references employees(id), avatar_url text);
create table employee_roles (id bigint generated by default as identity primary key, employee_id bigint references employees(id), role app_role not null);
create table system_users (
  id bigint generated by default as identity primary key,
  employee_id bigint not null unique references employees(id) on delete cascade,
  is_locked boolean not null default false,
  last_login timestamptz,
  created_at timestamptz not null default now()
);
create table role_proposals (id bigint generated by default as identity primary key, target_user_id bigint, target_user_name text, target_user_email text,
  proposed_role text not null check (proposed_role in ('EMPLOYEE','MANAGER','HR','ACCOUNTS','CEO','SYSTEM_ADMIN','DIRECTOR')), justification text, proposed_by_name text, proposed_at timestamptz default now(), status text default 'PENDING');
create table leave_types (id bigint generated by default as identity primary key, code text, name text, is_paid boolean);
create table leave_requests (id bigint generated by default as identity primary key, employee_id bigint references employees(id), leave_type_id bigint,
  from_date date, to_date date, total_days numeric, reason text, status text default 'PENDING', current_level int default 1,
  current_approver_id bigint references employees(id), timeline jsonb, closed_at timestamptz);
create table attendance_regularizations (id bigint generated by default as identity primary key, attendance_id bigint, employee_id bigint references employees(id),
  work_date date, requested_in text, requested_out text, reason text, status text default 'PENDING', approver_id bigint references employees(id), acted_at timestamptz);
create table attendance_records (id bigint generated by default as identity primary key, employee_id bigint references employees(id), work_date date, status text,
  punch_in timestamptz, punch_out timestamptz, worked_hours numeric(4,1), is_regularized boolean default false, remarks text, updated_at timestamptz default now(),
  unique (employee_id, work_date));
create table monthly_attendance_summaries (id bigint generated by default as identity primary key, employee_id bigint references employees(id), year int, month int, locked boolean default false);
create table holidays (id bigint generated by default as identity primary key, holiday_date date, name text, is_restricted boolean);
create table leave_balances (id bigint generated by default as identity primary key, employee_id bigint references employees(id), leave_type_id bigint, fy_year text, opening numeric default 0, accrued numeric default 0, used numeric default 0, reserved numeric default 0, encashed numeric default 0, lapsed numeric default 0);
alter table attendance_records enable row level security;
alter table leave_requests enable row level security;
alter table attendance_regularizations enable row level security;
alter table holidays enable row level security;
alter table leave_types enable row level security;
alter table system_users enable row level security;
alter table role_proposals enable row level security;
grant all on all tables in schema public to authenticated;

