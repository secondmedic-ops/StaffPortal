create or replace function public.current_employee_id()
returns bigint language sql stable security definer set search_path = public as $$
  select e.id from employees e
   where e.auth_user_id = auth.uid()
      or lower(e.official_email) = lower(coalesce(auth.jwt() ->> 'email', ''))
   order by (e.auth_user_id = auth.uid()) desc nulls last
   limit 1
$$;

create or replace function public.has_role(r text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from employee_roles er where er.employee_id = public.current_employee_id() and er.role::text = r)
$$;

create or replace function public.is_in_reporting_line(target bigint, mgr bigint default public.current_employee_id())
returns boolean language sql stable security definer set search_path = public as $$
  with recursive chain(id, manager_id, depth) as (
    select e.id, e.manager_id, 0 from employees e where e.id = target
    union all
    select e.id, e.manager_id, c.depth + 1 from employees e join chain c on e.id = c.manager_id where c.depth < 12
  )
  select mgr is not null and exists (select 1 from chain where manager_id = mgr)
$$;

-- Employees may only change their own contact details / login link; HR changes the rest.
create or replace function public.protect_employee_fields()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null or public.has_role('HR') or public.has_role('SYSTEM_ADMIN') then
    return new;
  end if;
  if new.emp_code is distinct from old.emp_code or new.full_name is distinct from old.full_name
     or new.official_email is distinct from old.official_email or new.department_id is distinct from old.department_id
     or new.employment_type is distinct from old.employment_type or new.status is distinct from old.status
     or new.manager_id is distinct from old.manager_id or new.date_of_joining is distinct from old.date_of_joining
     or new.date_of_exit is distinct from old.date_of_exit then
    raise exception 'Only HR can change employment details';
  end if;
  -- Designation may be updated by Accounts when a promotion is approved.
  if new.designation is distinct from old.designation and not public.has_role('ACCOUNTS') then
    raise exception 'Only HR can change designation';
  end if;
  if new.auth_user_id is distinct from old.auth_user_id and old.auth_user_id is not null then
    raise exception 'Login is already linked';
  end if;
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists employees_protect_fields on public.employees;
create trigger employees_protect_fields before update on public.employees
  for each row execute function public.protect_employee_fields();

