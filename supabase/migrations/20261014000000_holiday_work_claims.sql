-- =============================================================================
-- Holiday / Sunday work compensation: employee chooses comp-off OR overtime pay
-- =============================================================================
-- * Employee claims a holiday or week-off they worked, choosing COMP_OFF or OVERTIME.
-- * Reporting line (or HR) approves.
-- * COMP_OFF  → days credited to the employee's COMP_OFF leave balance (trigger).
-- * OVERTIME  → payroll adds overtime pay for approved days in that month.
-- Requires 20261013000000_staff_lifecycle.sql. Safe to re-run.
-- =============================================================================

create table if not exists public.holiday_work_claims (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete cascade,
  work_date date not null,
  worked_hours numeric(4,1),
  days numeric(3,1) not null check (days in (0.5, 1)),
  compensation text not null check (compensation in ('COMP_OFF', 'OVERTIME')),
  reason text,
  status text not null default 'PENDING' check (status in ('PENDING', 'APPROVED', 'REJECTED')),
  approver_id bigint references public.employees(id) on delete set null,
  approver_remarks text,
  acted_at timestamptz,
  created_at timestamptz not null default now(),
  unique (employee_id, work_date)
);

create index if not exists holiday_work_claims_status_idx on public.holiday_work_claims (status, work_date);

alter table public.holiday_work_claims enable row level security;

drop policy if exists holiday_work_claims_select on public.holiday_work_claims;
create policy holiday_work_claims_select on public.holiday_work_claims for select to authenticated
  using (employee_id = public.current_employee_id()
         or public.has_role('HR') or public.has_role('ACCOUNTS')
         or public.is_in_reporting_line(employee_id));

drop policy if exists holiday_work_claims_insert on public.holiday_work_claims;
create policy holiday_work_claims_insert on public.holiday_work_claims for insert to authenticated
  with check (employee_id = public.current_employee_id() and status = 'PENDING');

-- Employee may withdraw (delete) their own pending claim.
drop policy if exists holiday_work_claims_delete on public.holiday_work_claims;
create policy holiday_work_claims_delete on public.holiday_work_claims for delete to authenticated
  using (employee_id = public.current_employee_id() and status = 'PENDING');

drop policy if exists holiday_work_claims_update on public.holiday_work_claims;
create policy holiday_work_claims_update on public.holiday_work_claims for update to authenticated
  using (public.has_role('HR') or public.is_in_reporting_line(employee_id))
  with check (true);

-- Approval rules + comp-off credit
create or replace function public.process_holiday_work_claim()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  me bigint := public.current_employee_id();
  comp_type bigint;
  bal_id bigint;
  fy text;
begin
  if new.status is not distinct from old.status then
    return new;
  end if;

  if auth.uid() is not null then
    if old.employee_id = me then
      raise exception 'You cannot approve your own comp-off / overtime claim';
    end if;
    if old.status <> 'PENDING' then
      raise exception 'This claim is already %', old.status;
    end if;
    if not (public.is_in_reporting_line(old.employee_id, me) or public.has_role('HR')) then
      raise exception 'Only the reporting manager (or HR) can action this claim';
    end if;
    new.approver_id := me;
  end if;
  new.acted_at := now();

  if new.status = 'APPROVED' and new.compensation = 'COMP_OFF' then
    select id into comp_type from leave_types where upper(code) in ('COMP_OFF', 'COMPOFF', 'CO') order by id limit 1;
    if comp_type is null then
      raise exception 'No COMP_OFF leave type exists. Create one in Leave Policy Config, then approve again.';
    end if;

    select id into bal_id from leave_balances
     where employee_id = new.employee_id and leave_type_id = comp_type
     order by fy_year desc limit 1;

    if bal_id is null then
      fy := case when extract(month from new.work_date) >= 4
                 then extract(year from new.work_date)::int || '-' || (extract(year from new.work_date)::int + 1)
                 else (extract(year from new.work_date)::int - 1) || '-' || extract(year from new.work_date)::int end;
      insert into leave_balances (employee_id, leave_type_id, fy_year, opening, accrued, used, reserved, encashed, lapsed)
      values (new.employee_id, comp_type, fy, 0, new.days, 0, 0, 0, 0);
    else
      update leave_balances set accrued = accrued + new.days where id = bal_id;
    end if;
  end if;
  return new;
end $$;

drop trigger if exists holiday_work_claims_process on public.holiday_work_claims;
create trigger holiday_work_claims_process
  before update on public.holiday_work_claims
  for each row execute function public.process_holiday_work_claim();

grant select, insert, update, delete on public.holiday_work_claims to authenticated;

-- =============================================================================
-- Monthly payroll is approved by the reporting manager of whoever computed it
-- =============================================================================
-- Accounts computes & saves DRAFT → the computer's reporting line approves
-- (DRAFT → APPROVED) or sends back (APPROVED → DRAFT) → Accounts publishes
-- (APPROVED → PUBLISHED). Approvers can read entries and change status only.

drop policy if exists payroll_entries_select on public.payroll_entries;
create policy payroll_entries_select on public.payroll_entries for select to authenticated
  using (public.has_role('ACCOUNTS')
         or (status in ('DRAFT', 'APPROVED') and computed_by is not null and public.is_in_reporting_line(computed_by))
         or (employee_id = public.current_employee_id() and status = 'PUBLISHED'));

drop policy if exists payroll_entries_ceo_update on public.payroll_entries;
drop policy if exists payroll_entries_approver_update on public.payroll_entries;
create policy payroll_entries_approver_update on public.payroll_entries for update to authenticated
  using (computed_by is not null and public.is_in_reporting_line(computed_by))
  with check (true);

create or replace function public.enforce_payroll_approval()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  me bigint := public.current_employee_id();
  is_accounts boolean := public.has_role('ACCOUNTS');
  is_approver boolean := old.computed_by is not null and public.is_in_reporting_line(old.computed_by, me);
begin
  if auth.uid() is null then
    return new;
  end if;

  -- Only Accounts changes amounts or who computed the entry.
  if not is_accounts and (
       new.gross_earnings is distinct from old.gross_earnings
    or new.total_deductions is distinct from old.total_deductions
    or new.net_pay is distinct from old.net_pay
    or new.payable_days is distinct from old.payable_days
    or new.earnings is distinct from old.earnings
    or new.deductions is distinct from old.deductions
    or new.computed_by is distinct from old.computed_by) then
    raise exception 'Only Accounts can change payroll amounts';
  end if;

  if new.status is distinct from old.status then
    if new.status = 'APPROVED' then
      if old.computed_by = me then
        raise exception 'Payroll must be approved by your reporting manager, not by the person who computed it';
      end if;
      if not is_approver then
        raise exception 'Only the reporting manager of the Accounts person who computed this payroll can approve it';
      end if;
    elsif new.status = 'PUBLISHED' then
      if old.status <> 'APPROVED' then
        raise exception 'Payroll must be approved by the reporting manager before publishing';
      end if;
      if not is_accounts then
        raise exception 'Only Accounts publishes payslips';
      end if;
    elsif new.status = 'DRAFT' and old.status = 'APPROVED' and not (is_approver or is_accounts) then
      raise exception 'Only the approver or Accounts can send payroll back';
    end if;
  end if;
  return new;
end $$;

drop trigger if exists payroll_entries_enforce_approval on public.payroll_entries;
create trigger payroll_entries_enforce_approval
  before update on public.payroll_entries
  for each row execute function public.enforce_payroll_approval();
